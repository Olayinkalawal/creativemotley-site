// Watch the work: writes the video cards in src/partials/showcase.html from docs/videos.json (owner: track O1).
//   node src/partials/showcase.videos.mjs           rewrite the cards between <!-- videos:start --> and <!-- videos:end -->
//   node src/partials/showcase.videos.mjs --check   exit 1 if the cards are out of date
// One card per creator, in videos.json order: the creator's first video (the "use" pick in docs/copy-drafts.md).
// To change a video, edit its id in docs/videos.json, give its display title a fact in docs/facts.json (kind "draft"
// until the client approves; `url` = https://www.youtube.com/watch?v=<id>), and run this script. A video whose id has
// no fact is left out (no untraced copy on the page). The ids are unverified until the client confirms them.
// Card art: public/assets/thumbs/video/<slug>-{640,1280,1920}.{avif,webp} (the creator's poster, composed 16:9) is the
// fallback; with JS the YouTube thumbnail replaces it once Showcase is near (src/sections/showcase.js).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const videos = read('docs/videos.json');
const facts = read('docs/facts.json');
const factFor = (id) => facts.find((f) => typeof f.url === 'string' && new URL(f.url, 'https://x').searchParams.get('v') === id);
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const cards = [];
for (const c of videos.creators) {
  const v = (c.videos || []).find((x) => factFor(x.id));
  if (!v) { console.warn(`no traced video for ${c.creator}: skipped`); continue; }
  const f = factFor(v.id);
  const slug = path.basename(c.poster || '', '.webp');
  cards.push({ id: v.id, slug, name: c.creator, title: f.claim, draft: f.kind === 'draft' ? f.id : '' });
}
const art = (slug, fmt) => [640, 1280, 1920].map((w) => `/assets/thumbs/video/${slug}-${w}.${fmt} ${w}w`).join(', ');
// the card is ~84% of the column on desktop (≈ 860 px at 1440), ~86vw on phones
const SIZES = '(max-width: 719px) 86vw, (max-width: 1023px) 78vw, min(64vw, 960px)';
const li = (c, i) => {
  const n = i + 1, d = (id) => (id ? ` data-draft="${id}"` : '');
  return `            <li class="wv__item" data-yt="${c.id}" data-slug="${c.slug}">
              <article class="wv__card">
                <button class="wv__play" type="button" aria-haspopup="dialog" aria-labelledby="wv-cta-${n} wv-t-${n}" data-wv-play>
                  <picture class="wv__art"><source type="image/avif" srcset="${art(c.slug, 'avif')}" sizes="${SIZES}"><source type="image/webp" srcset="${art(c.slug, 'webp')}" sizes="${SIZES}"><img src="/assets/thumbs/video/${c.slug}-1280.webp" alt="" width="1920" height="1080" loading="lazy" decoding="async"></picture>
                  <span class="wv__icon" aria-hidden="true"></span>
                  <span class="wv__cta" id="wv-cta-${n}" data-draft="DC61">Play video</span>
                </button>
                <div class="wv__meta">
                  <p class="wv__by">${esc(c.name)}</p>
                  <h4 class="wv__t" id="wv-t-${n}"${d(c.draft)}>${esc(c.title)}</h4>
                  <a class="boxlink wv__yt" href="https://www.youtube.com/watch?v=${c.id}" target="_blank" rel="noopener" data-draft="DC62">Watch on YouTube <span class="ar">↗</span></a>
                </div>
              </article>
            </li>`;
};
const block = `<!-- videos:start (generated by src/partials/showcase.videos.mjs from docs/videos.json: edit there, then re-run) -->
${cards.map(li).join('\n')}
            <!-- videos:end -->`;

const file = path.join(root, 'src/partials/showcase.html');
const html = fs.readFileSync(file, 'utf8');
const re = /<!-- videos:start[\s\S]*?<!-- videos:end -->/;
if (!re.test(html)) { console.error('markers not found in showcase.html'); process.exit(2); }
const next = html.replace(re, block).replace(/(data-wv-total>)\d+/, `$1${String(cards.length).padStart(2, '0')}`);
if (process.argv.includes('--check')) {
  if (next !== html) { console.error('showcase.html video cards are out of date: run node src/partials/showcase.videos.mjs'); process.exit(1); }
  console.log(`ok: ${cards.length} cards`);
} else {
  fs.writeFileSync(file, next);
  console.log(`${cards.length} cards: ${cards.map((c) => `${c.name} (${c.id})`).join(', ')}`);
}
