#!/usr/bin/env python3
"""Directors film: take the Knicks logo (and the maker's side flag) off the left portrait's cap.

The client (2026-10-31): "keep kunle, remove the knicks logo". The cap of the left portrait (Olayinka Lawal) in the
Directors alpha film carries a Knicks logo on its front and a small New Era flag on its left side, by the brim; our
standing rule is no third-party marks in our art, so both go. Nothing else changes: the faces, glasses, beard, ruff,
clothes, the right portrait, the torn-paper matte, the alpha, the timing and the motion are left exactly as they are.

Usage
  python3 scripts/retouch-directors-cap.py build [--master M]
        (re)make the patch assets in scripts/assets/directors-cap/ from frame 0 of the master (deterministic)
  python3 scripts/retouch-directors-cap.py run --in M --out clean.mkv [--fill] [--log track.json]
        the whole film: M decoded (libvpx-vp9 for WebM, so the alpha survives) -> retouch -> FFV1 (yuva420p, level 3,
        16 slices: the same intermediate scripts/encode-directors.sh makes). --fill also applies encode-directors.sh's
        flatten (transparent pixels get a smooth fill, alpha < 8 -> 0, > 247 -> 255), so the file is that script's
        flat.mkv, ready for its two VP9 passes.
  ... | python3 scripts/retouch-directors-cap.py run --raw 1920x1080 [--fill] [--log track.json] | ...
        a filter: raw RGBA frames on stdin -> raw RGBA frames on stdout. Frame 0 of the stream must be the master's
        frame 0 (the tracker's reference; checked against the assets).
  python3 scripts/retouch-directors-cap.py still --in M --out directors-poster.webp
        the poster: the clean frame 0, as public/assets/video/directors-poster.webp was made from the master's frame 0
        (PIL LANCZOS to 1600x900, RGBA, WebP quality 80, method 6: that recipe reproduces the old poster byte for byte)

Inputs
  The master is the client's live file (https://creativemotley.com/directors/directors.webm, 1920x1080, 30 fps,
  600 frames, VP9 + alpha), by default $DIRECTORS_MASTER or /home/user/cm-film/source/site/directors/directors.webm.
  Decode it with "-c:v libvpx-vp9 -i": ffmpeg's native VP9 decoder drops the alpha.

Method (two regions, each done the same way; deterministic, no AI anywhere)
  Reference frame: frame 0 (the frame the poster and the still pair are made from; the head faces front there).
  Boxes (frame px): logo (300, 100)-(552, 280), flag (612, 268)-(668, 346); the tracker searches CAP_ROI.
  1. Assets (build, from frame 0; scripts/assets/directors-cap/, regenerated byte for byte by "build"):
     - segmentation: the logo is the largest non-blue blob on the crown (Lab b >= -12 or L >= 45) with its holes
       filled; the flag is the largest orange outline (Lab a > 15, b > 20) on the side panel, filled. The brim
       (orange components in the box's lower half that touch its lower edge or span half its width) is never part
       of either.
     - core (*-core.png): the mark grown by 9 px (logo) / 4 px (flag): its dark embroidery rim, the compression
       ringing and fabric pucker round it (the crown's gradient energy is raised out to ~10 px from the logo, ~4 px
       from the flag) and margin for the tracker's residual. This is what gets repainted.
     - mask (*-mask.png): 1 on the core and a 6 px (logo) / 5 px (flag) smoothstep feather outward over plain crown.
     - plate (*-plate.png): frame 0's box, with plain cap fabric over the core (and over the few px of frame 0's
       brim edge that lie under the mask: the brim moves against the logo as the head turns, so those pixels are
       crown in other frames):
       shading = a membrane (Laplace) fill of the surrounding crown's low-pass colour (sigma 2.5), so the light
         runs on smoothly across the front panel;
       grain = the crown's own texture (Y / lowpass(Y) - 1) quilted in from plain crown pixels of the same box
         (12 px blocks every 8 px, each matched by masked SSD on what is already there; near-ties drawn with a
         fixed seed), multiplied onto the shading.
       Outside that the plate is frame 0 itself. No seam or mark is invented: the front panel shows no centre seam
       above the logo, so none is drawn under it; the side panel's seam, the eyelets and the button are outside
       both masks.
  2. Tracking (run): each mark and the crown around it (14 / 10 px, never the brim or its junction line) is
     matched to frame 0's box by ECC (OpenCV findTransformECCWithMask: a homography for the logo, an affine for the
     flag), started from the previous frame's warp but always measured against frame 0, so it never drifts. No
     temporal smoothing: the source moves on a 5-frame cadence (two near-still frames, two small steps, one large
     one) and the patch has to take the same steps.
  3. Per frame, in the box's own coordinates (the frame warped back with the tracked warp):
     - the brim is found again (it slides against the logo as the head turns); the mask is 0 on it and on its dark
       junction line (3 px above the orange), except where the logo itself lies on them;
     - where the logo itself (+3 px) lies on that junction line (only its lowest point, near frame 0's pose), the
       line is the frame's own, interpolated along each row from the line's pixels either side of it; the rest of
       the line is never touched; where its very tip dips into the brim's top edge, those few pixels take the
       brim's colour from the orange either side, along the row;
     - elsewhere in the core: plate + correction, where the correction is the low-pass (sigma 2) difference
       frame - plate measured on the ring round the core (feather + 3 px, brim and junction excluded) and carried
       into the core by a membrane, so the patch takes on the frame's light and shading as the head turns;
     - the patch and the mask are warped forward (Lanczos / bilinear) and blended in:
       out = frame + mask * (patch - frame), rounded. Alpha is never touched; outside the warped mask every RGBA
       byte is the input's (QA: max |diff| outside the mask = 0 over all 600 frames).
  DIRECTORS_CAP_ASSETS=<dir> reads / writes the assets elsewhere (for trials).
"""
