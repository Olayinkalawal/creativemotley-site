# ── small helpers ──────────────────────────────────────────────────────────────────────────────────────────────────
def lab_parts(rgb):
    lab = cv2.cvtColor(np.ascontiguousarray(rgb), cv2.COLOR_RGB2Lab).astype(np.float32)
    return lab[..., 0] / 2.55, lab[..., 1] - 128, lab[..., 2] - 128


def disk(r):
    return cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * r + 1, 2 * r + 1))


def lowpass(img, valid, sigma):
    """normalised Gaussian: the mean of the valid pixels around each pixel"""
    v = valid.astype(np.float32)
    num = cv2.GaussianBlur(img * (v[..., None] if img.ndim == 3 else v), (0, 0), sigma)
    den = cv2.GaussianBlur(v, (0, 0), sigma)
    den = np.maximum(den, 1e-6)
    return num / (den[..., None] if img.ndim == 3 else den)


def brim_mask(rgb, split=False):
    """the orange brim: orange components (4-connected) in the box's lower half that touch its lower edge or span
    half its width (not the torn-paper matte round the crown's top), with its pinholes filled"""
    _, a, b = lab_parts(rgb)
    orange = ((a > 15) & (b > 20)).astype(np.uint8)
    n, lbl, st, cen = cv2.connectedComponentsWithStats(orange, connectivity=4)
    keep = np.zeros(n, bool)
    keep[np.unique(lbl[-1])] = True
    keep |= st[:, cv2.CC_STAT_WIDTH] >= orange.shape[1] // 2
    keep &= cen[:, 1] > orange.shape[0] / 2
    keep[0] = False
    brim = keep[lbl]
    # its pinholes (paler pixels of the brim's own highlight, enclosed by brim) are brim too
    n, lbl, st, _ = cv2.connectedComponentsWithStats((~brim).astype(np.uint8), connectivity=4)
    edge = np.unique(np.concatenate([lbl[0], lbl[-1], lbl[:, 0], lbl[:, -1]]))
    holes = np.zeros(n, bool)
    holes[1:] = st[1:, cv2.CC_STAT_AREA] <= 64
    holes[edge] = False
    holes = holes[lbl]
    return (brim, holes) if split else brim | holes


def fill_holes(m):
    cnts, _ = cv2.findContours(m.astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    out = np.zeros(m.shape, np.uint8)
    cv2.drawContours(out, cnts, -1, 1, -1)
    return out.astype(bool)


def largest(m, conn=8):
    n, lbl, st, _ = cv2.connectedComponentsWithStats(m.astype(np.uint8), connectivity=conn)
    if n < 2:
        raise SystemExit('segmentation found nothing')
    return lbl == (1 + int(np.argmax(st[1:, cv2.CC_STAT_AREA])))


def segment(name, rgb, brim):
    L, a, b = lab_parts(rgb)
    fx0, fy0, fx1, fy1 = REGIONS[name]['find']
    win = np.zeros(L.shape, bool)
    win[fy0:fy1, fx0:fx1] = True
    if name == 'logo':
        cand = ~((b < -12) & (L < 45)) & ~brim & win
    else:
        cand = (a > 15) & (b > 20) & ~brim & win
    return fill_holes(largest(cand))


def brim_dist(brim):
    """distance (px) of every pixel to the brim"""
    if not brim.any():
        return np.full(brim.shape, 1e3, np.float32)
    return cv2.distanceTransform((~brim).astype(np.uint8), cv2.DIST_L2, 5)


class Membrane:
    """Laplace fill of the unknown pixels U from their known 4-neighbours; neighbours in `blocked` are not used
    (a free edge), and the vertical coupling is weighted by wv (0..1) so the fill can be made to run along rows."""

    def __init__(self, U, blocked, wv):
        h, w = U.shape
        self.U = U
        idx = -np.ones((h, w), np.int64)
        ys, xs = np.nonzero(U)
        idx[ys, xs] = np.arange(len(ys))
        n = len(ys)
        rows, cols, vals = [], [], []          # system matrix
        brow, bcol, bval = [], [], []          # rhs = B @ known.ravel()
        diag = np.zeros(n)
        for dy, dx in ((0, 1), (0, -1), (1, 0), (-1, 0)):
            ny, nx = ys + dy, xs + dx
            inside = (ny >= 0) & (ny < h) & (nx >= 0) & (nx < w)
            k = np.nonzero(inside)[0]
            py, px, qy, qx = ys[k], xs[k], ny[k], nx[k]
            ok = ~blocked[qy, qx]
            k, py, px, qy, qx = k[ok], py[ok], px[ok], qy[ok], qx[ok]
            wt = np.ones(len(k)) if dy == 0 else np.minimum(wv[py, px], wv[qy, qx]).astype(np.float64)
            diag += np.bincount(k, weights=wt, minlength=n)
            unk = U[qy, qx]
            rows += [k[unk]]; cols += [idx[qy[unk], qx[unk]]]; vals += [-wt[unk]]
            kn = ~unk
            brow += [k[kn]]; bcol += [qy[kn] * w + qx[kn]]; bval += [wt[kn]]
        rows = np.concatenate(rows + [np.arange(n)]); cols = np.concatenate(cols + [np.arange(n)])
        vals = np.concatenate(vals + [diag])
        self.lu = splu(csr_matrix(coo_matrix((vals, (rows, cols)), shape=(n, n))).tocsc())
        self.B = csr_matrix(coo_matrix((np.concatenate(bval), (np.concatenate(brow), np.concatenate(bcol))),
                                       shape=(n, h * w)))
        self.ys, self.xs = ys, xs

    def solve(self, known):
        """known: (h, w, c) float; returns the values at the unknown pixels, (n, c)"""
        h, w, c = known.shape
        rhs = self.B @ known.reshape(h * w, c).astype(np.float64)
        return np.stack([self.lu.solve(rhs[:, i]) for i in range(c)], 1)


def quilt(t, known, donor, target, block=12, step=8, tol=0.08, seed=SEED):
    """fill t at `target` pixels with blocks of t copied from `donor` pixels, each block matched (masked SSD) on the
    pixels already there; ties within tol of the best are drawn with a fixed seed. Deterministic."""
    rng = np.random.default_rng(seed)
    out = t.astype(np.float32).copy()
    filled = known & ~target
    h, w = t.shape
    okpos = cv2.erode(donor.astype(np.uint8), np.ones((block, block), np.uint8), anchor=(0, 0),
                      borderType=cv2.BORDER_CONSTANT, borderValue=0)[:h - block + 1, :w - block + 1].astype(bool)
    src = np.ascontiguousarray(out)
    ys, xs = np.nonzero(target)
    y0, y1 = max(0, ys.min() - block // 2), min(h - block, ys.max())
    x0, x1 = max(0, xs.min() - block // 2), min(w - block, xs.max())
    for by in list(range(y0, y1, step)) + [y1]:
        for bx in list(range(x0, x1, step)) + [x1]:
            win = (slice(by, by + block), slice(bx, bx + block))
            todo = target[win] & ~filled[win]
            if not todo.any():
                continue
            m = filled[win].astype(np.float32)
            if m.sum() < 1:
                err = np.zeros(okpos.shape, np.float32)
            else:
                err = cv2.matchTemplate(src, np.ascontiguousarray(out[win] * m), cv2.TM_SQDIFF, mask=m)
            err = np.where(okpos, err, np.inf)
            best = float(err.min())
            cy, cx = np.nonzero(err <= best * (1 + tol) + 1e-9)
            j = int(rng.integers(len(cy)))
            patch = src[cy[j]:cy[j] + block, cx[j]:cx[j] + block]
            sub = out[win]
            sub[todo] = patch[todo]
            filled[win] |= todo
    return out


# ── assets ─────────────────────────────────────────────────────────────────────────────────────────────────────────
def build_region(name, frame0):
    cfg = REGIONS[name]
    x0, y0, x1, y1 = cfg['box']
    rgb = frame0[y0:y1, x0:x1, :3].copy()
    alpha = frame0[y0:y1, x0:x1, 3]
    brim = brim_mask(rgb)
    mark = segment(name, rgb, brim)
    core = cv2.dilate(mark.astype(np.uint8), disk(cfg['grow'])).astype(bool)
    # composite mask: 1 on the core, smoothstep feather outward (the brim is cut per frame, where it then is)
    dist = cv2.distanceTransform((~core).astype(np.uint8), cv2.DIST_L2, 5)
    s = np.clip(1 - dist / cfg['feather'], 0, 1)
    mask = np.where(core, 1.0, s * s * (3 - 2 * s))
    if (mask[[0, -1], :] > 0).any() or (mask[:, [0, -1]] > 0).any():
        raise SystemExit(f'{name}: the mask reaches the box edge')
    if (alpha[mask > 0] < 255).any():
        raise SystemExit(f'{name}: the mask reaches transparent pixels')
    # the plate is plain crown over the whole core, and also wherever frame 0's brim or junction line lies under the
    # mask: as the head turns the brim moves against the logo, so those pixels can land on crown in other frames
    edge = brim | (brim_dist(brim) <= JUNCTION + 1)
    U = core | ((mask > 0) & edge)
    blocked = edge & ~U
    f = rgb.astype(np.float32)
    valid = ~U & ~edge
    base = f.copy()
    base[U] = Membrane(U, blocked, np.ones(U.shape, np.float32)).solve(lowpass(f, valid, GRAIN_SIGMA))
    # grain: the crown's own texture, quilted in
    Y = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY).astype(np.float32)
    t = Y / np.maximum(lowpass(Y, valid, GRAIN_SIGMA), 1.0) - 1
    Lc, _, bc = lab_parts(rgb)
    crown = (bc < -12) & (Lc < 45)
    donor = cv2.erode(crown.astype(np.uint8), disk(2)).astype(bool) & \
        ~cv2.dilate((U | edge).astype(np.uint8), disk(3)).astype(bool)
    tq = quilt(t, valid, donor, U)
    plate = f.copy()
    plate[U] = base[U] * (1 + tq[U, None])
    plate = np.clip(np.round(plate), 0, 255).astype(np.uint8)
    return dict(plate=plate, core=core, mask=mask, mark=mark, brim=brim, fill=U)


def save_assets(frame0):
    ASSETS.mkdir(parents=True, exist_ok=True)
    meta = {'reference': 'master frame 0', 'size': [W, H], 'cap_roi': CAP_ROI, 'regions': {}}
    for name in REGIONS:
        r = build_region(name, frame0)
        cv2.imwrite(str(ASSETS / f'{name}-plate.png'), cv2.cvtColor(r['plate'], cv2.COLOR_RGB2BGR),
                    [cv2.IMWRITE_PNG_COMPRESSION, 9])
        cv2.imwrite(str(ASSETS / f'{name}-core.png'), r['core'].astype(np.uint8) * 255, [cv2.IMWRITE_PNG_COMPRESSION, 9])
        cv2.imwrite(str(ASSETS / f'{name}-mask.png'), np.round(r['mask'] * 255).astype(np.uint8),
                    [cv2.IMWRITE_PNG_COMPRESSION, 9])
        c = REGIONS[name]
        meta['regions'][name] = {'box': c['box'], 'grow': c['grow'], 'feather': c['feather'],
                                 'core_px': int(r['core'].sum()), 'mask_px': int((r['mask'] > 0).sum())}
        print(f'{name}: core {int(r["core"].sum())} px, mask {int((r["mask"] > 0).sum())} px', file=sys.stderr)
    (ASSETS / 'meta.json').write_text(json.dumps(meta, indent=1) + '\n')


# ── the retoucher ──────────────────────────────────────────────────────────────────────────────────────────────────
class Region:
    def __init__(self, name):
        cfg = REGIONS[name]
        self.name, self.cfg = name, cfg
        self.box = cfg['box']
        self.plate = cv2.cvtColor(cv2.imread(str(ASSETS / f'{name}-plate.png')), cv2.COLOR_BGR2RGB)
        self.core = cv2.imread(str(ASSETS / f'{name}-core.png'), cv2.IMREAD_GRAYSCALE) > 127
        self.mask = cv2.imread(str(ASSETS / f'{name}-mask.png'), cv2.IMREAD_GRAYSCALE).astype(np.float32) / 255
        self.plate_f = self.plate.astype(np.float32)
        self.ring0 = cv2.dilate((self.mask > 0).astype(np.uint8), disk(3)).astype(bool) & ~self.core
        self.near = cv2.dilate(self.core.astype(np.uint8), disk(1)).astype(bool)
        self._mem = (None, None)
        self.tmpl = None
        self.warp = None

    def start(self, frame0):
        """frame 0 of the input: check it is the master's, take the tracking template from it"""
        x0, y0, x1, y1 = self.box
        rgb = frame0[y0:y1, x0:x1, :3]
        brim = brim_mask(rgb)
        edge = brim | (brim_dist(brim) <= JUNCTION + 1)
        outside = ~cv2.dilate((self.core | ((self.mask > 0) & edge)).astype(np.uint8), disk(2)).astype(bool)
        d = np.abs(rgb.astype(np.float32) - self.plate_f)[outside].mean()
        if d > 1.5:
            raise SystemExit(f'{self.name}: frame 0 is not the master\'s frame 0 (mean diff {d:.2f} around the mark)')
        self.tmpl = cv2.cvtColor(np.ascontiguousarray(rgb), cv2.COLOR_RGB2GRAY).astype(np.float32)
        mark = segment(self.name, rgb, brim)
        self.markg = cv2.dilate(mark.astype(np.uint8), disk(3)).astype(bool)   # the mark itself, +3 px
        # the template is the mark and the crown around it, never the brim (the brim moves against the logo)
        tm = cv2.dilate(mark.astype(np.uint8), disk(self.cfg['tmpl_grow'])).astype(bool)
        tm &= ~cv2.dilate(edge.astype(np.uint8), disk(3)).astype(bool)
        self.tmask = tm.astype(np.uint8) * 255
        rx, ry = CAP_ROI[:2]
        self.warp = np.array([[1, 0, x0 - rx], [0, 1, y0 - ry], [0, 0, 1]], np.float32)
        if self.cfg['motion'] != cv2.MOTION_HOMOGRAPHY:
            self.warp = self.warp[:2].copy()

    def track(self, gray_roi):
        crit = (cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_COUNT, 200, 1e-7)
        ones = np.full(gray_roi.shape, 255, np.uint8)
        try:
            cc, wp = cv2.findTransformECCWithMask(self.tmpl, gray_roi, self.tmask, ones, self.warp.copy(),
                                                  self.cfg['motion'], crit, 5)
        except cv2.error as e:   # never seen on the master; keep the last warp rather than stop
            print(f'{self.name}: ECC failed ({str(e)[:80]}), last warp kept', file=sys.stderr)
            return -1.0
        self.warp = wp
        return float(cc)

    def H(self):
        """3x3: box pixels -> CAP_ROI pixels"""
        return self.warp if self.warp.shape[0] == 3 else np.vstack([self.warp, [0, 0, 1]]).astype(np.float32)

    def membrane(self, C, blocked):
        key = (C.tobytes(), (blocked & self.near).tobytes())
        if self._mem[0] != key:
            self._mem = (key, Membrane(C, blocked, np.ones(C.shape, np.float32)))
        return self._mem[1]

    def patch(self, back):
        """the clean box for this frame, from the frame warped back into the box. Returns (patch, mask)"""
        orange, holes = brim_mask(np.clip(back, 0, 255).astype(np.uint8), split=True)
        brim = orange | holes                                          # where the brim is in this frame
        junc = ~brim & (brim_dist(brim) <= JUNCTION)                  # its dark junction line with the crown
        J = junc & self.markg                                          # the mark itself, on the junction line
        C = self.core & ~brim & ~junc
        ring = self.ring0 & ~brim & ~junc
        # colour: the frame's low-pass minus the plate's, on the ring, carried into the core by a membrane
        diff = lowpass(back, ring, CORR_SIGMA) - lowpass(self.plate_f, ring, CORR_SIGMA)
        known = np.zeros_like(diff)
        known[ring] = diff[ring]
        corr = known.copy()
        corr[C] = self.membrane(C, brim | junc).solve(known)
        patch = self.plate_f + corr
        # the junction line under the mark: the frame's own line, interpolated along each row from the nearest
        # pixels either side that are neither the mark (+3 px) nor the brim (the rest of the line is left as it is)
        if J.any():
            ok = ~self.markg & ~brim
            xs = np.arange(ok.shape[1])
            for y in np.unique(np.nonzero(J)[0]):
                li = np.maximum.accumulate(np.where(ok[y], xs, -1))
                ri = np.minimum.accumulate(np.where(ok[y], xs, 10 ** 6)[::-1])[::-1]
                for x in np.nonzero(J[y])[0]:
                    l, r = li[x], ri[x]
                    if l < 0 and r >= ok.shape[1]:
                        continue
                    if l < 0:
                        patch[y, x] = back[y, r]
                    elif r >= ok.shape[1]:
                        patch[y, x] = back[y, l]
                    else:
                        u = (x - l) / (r - l)
                        patch[y, x] = back[y, l] * (1 - u) + back[y, r] * u
        # the logo's lowest point where it dips into the brim's top edge (a few px, enclosed by brim): the brim's
        # own colour, interpolated along the row from the orange either side
        HJ = holes & self.markg
        for y in np.unique(np.nonzero(HJ)[0]):
            xs_ok = np.nonzero(orange[y])[0]
            for x in np.nonzero(HJ[y])[0]:
                lft, rgt = xs_ok[xs_ok < x], xs_ok[xs_ok > x]
                if len(lft) and len(rgt) and rgt[0] - lft[-1] <= 24:
                    u = (x - lft[-1]) / (rgt[0] - lft[-1])
                    patch[y, x] = back[y, lft[-1]] * (1 - u) + back[y, rgt[0]] * u
                else:
                    HJ[y, x] = False
        mask = self.mask.copy()
        mask[brim | (junc & ~J)] = 0              # the brim and its line are never touched beyond the mark
        mask[J | HJ] = 1
        return patch, mask

    def apply(self, roi_rgb):
        """roi_rgb: the frame's CAP_ROI, RGB uint8 (modified in place). Returns the warped mask's bounds and values"""
        bw, bh = self.box[2] - self.box[0], self.box[3] - self.box[1]
        Hm = self.H().astype(np.float64)
        back = cv2.warpPerspective(roi_rgb, Hm, (bw, bh), flags=cv2.INTER_LINEAR | cv2.WARP_INVERSE_MAP,
                                   borderMode=cv2.BORDER_REPLICATE).astype(np.float32)
        patch, mask = self.patch(back)
        # forward: into the bounding box of the warped box
        cs = cv2.perspectiveTransform(np.array([[[0, 0]], [[bw, 0]], [[bw, bh]], [[0, bh]]], np.float64), Hm)[:, 0]
        rh, rw = roi_rgb.shape[:2]
        ox, oy = max(0, int(np.floor(cs[:, 0].min())) - 2), max(0, int(np.floor(cs[:, 1].min())) - 2)
        ex, ey = min(rw, int(np.ceil(cs[:, 0].max())) + 2), min(rh, int(np.ceil(cs[:, 1].max())) + 2)
        T = np.array([[1, 0, -ox], [0, 1, -oy], [0, 0, 1]], np.float64) @ Hm
        P = cv2.warpPerspective(patch, T, (ex - ox, ey - oy), flags=cv2.INTER_LANCZOS4, borderMode=cv2.BORDER_REPLICATE)
        M = cv2.warpPerspective(mask, T, (ex - ox, ey - oy), flags=cv2.INTER_LINEAR,
                                borderMode=cv2.BORDER_CONSTANT, borderValue=0)
        sel = M > 0
        O = roi_rgb[oy:ey, ox:ex]
        Of = O[sel].astype(np.float32)
        O[sel] = np.clip(np.round(Of + M[sel, None] * (P[sel] - Of)), 0, 255).astype(np.uint8)
        return (ox, oy, ex, ey), M


class Retoucher:
    def __init__(self):
        if not (ASSETS / 'logo-plate.png').exists():
            raise SystemExit(f'no assets in {ASSETS}: run "build" first')
        self.regions = [Region(n) for n in REGIONS]
        self.n = 0
        self.log = []

    def __call__(self, frame):
        """frame: (H, W, 4) RGBA uint8, modified in place; returns {region: (bounds in frame px, mask)}"""
        if self.n == 0:
            for r in self.regions:
                r.start(frame)
        rx0, ry0, rx1, ry1 = CAP_ROI
        roi = frame[ry0:ry1, rx0:rx1]
        rgb = np.ascontiguousarray(roi[..., :3])
        gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY).astype(np.float32)
        rec, info = {'frame': self.n}, {}
        for r in self.regions:
            cc = r.track(gray)            # every region is tracked on the untouched frame
            rec[r.name] = {'cc': round(cc, 5), 'warp': np.round(r.H(), 6).tolist()}
        for r in self.regions:
            (ox, oy, ex, ey), M = r.apply(rgb)
            info[r.name] = ((ox + rx0, oy + ry0, ex + rx0, ey + ry0), M)
        roi[..., :3] = rgb
        self.log.append(rec)
        self.n += 1
        return info


# ── encode-directors.sh's flatten, verbatim ────────────────────────────────────────────────────────────────────────
def flatten(f):
    def down(img, k):
        h, w = img.shape[:2]
        return cv2.resize(img, (max(1, w // k), max(1, h // k)), interpolation=cv2.INTER_AREA)
    Hh, Ww = f.shape[:2]
    rgb = np.ascontiguousarray(f[..., :3]); a = f[..., 3]
    m = (a >= 200).astype(np.uint8)
    levels = [(down(cv2.bitwise_and(rgb, rgb, mask=m).astype(np.float32), 8), down(m.astype(np.float32), 8))]
    for _ in range(3): levels.append((down(levels[-1][0], 4), down(levels[-1][1], 4)))
    sh = levels[0][1].shape[:2][::-1]; acc = None
    for P, Wt in reversed(levels):
        Pb = cv2.GaussianBlur(P, (5, 5), 0); Wb = cv2.GaussianBlur(Wt, (5, 5), 0)
        F = cv2.resize(Pb / np.maximum(Wb, 1e-5)[..., None], sh, interpolation=cv2.INTER_CUBIC)
        c = np.clip(cv2.resize(Wb, sh, interpolation=cv2.INTER_LINEAR) * 12.0, 0, 1)[..., None]
        acc = F if acc is None else F * c + acc * (1 - c)
    fill = np.clip(cv2.resize(acc, (Ww, Hh), interpolation=cv2.INTER_CUBIC), 0, 255).astype(np.uint8)
    a2 = a.copy(); a2[a2 < 8] = 0; a2[a2 > 247] = 255
    o = rgb.copy(); z = a2 == 0; o[z] = fill[z]
    return np.dstack([o, a2])


# ── I/O ────────────────────────────────────────────────────────────────────────────────────────────────────────────
def decoder(path, frames=None):
    cmd = ['ffmpeg', '-nostdin', '-hide_banner', '-loglevel', 'error']   # -nostdin: never eat a caller's stdin
    if str(path).endswith('.webm'):
        cmd += ['-c:v', 'libvpx-vp9']
    cmd += ['-i', str(path)]
    if frames:
        cmd += ['-frames:v', str(frames)]
    cmd += ['-f', 'rawvideo', '-pix_fmt', 'rgba', '-']
    return subprocess.Popen(cmd, stdout=subprocess.PIPE)


def frames_of(stream, w, h):
    n = w * h * 4
    while True:
        buf = stream.read(n)
        if len(buf) < n:
            return
        yield np.frombuffer(buf, np.uint8).reshape(h, w, 4).copy()


def first_frame(path):
    p = decoder(path, frames=1)
    f = next(frames_of(p.stdout, W, H))
    p.stdout.close(); p.wait()
    return f


def cmd_build(args):
    save_assets(first_frame(args.master))


def cmd_run(args):
    rt = Retoucher()
    if args.raw:
        w, h = (int(v) for v in args.raw.split('x'))
        src, enc = sys.stdin.buffer, None
        sink = sys.stdout.buffer
    else:
        w, h = W, H
        dec = decoder(args.inp)
        src = dec.stdout
        enc = subprocess.Popen(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-f', 'rawvideo', '-pix_fmt',
                                'rgba', '-s', f'{w}x{h}', '-r', str(args.fps), '-i', '-', '-c:v', 'ffv1', '-level', '3',
                                '-slices', '16', '-pix_fmt', 'yuva420p', args.out], stdin=subprocess.PIPE)
        sink = enc.stdin
    if (w, h) != (W, H):
        raise SystemExit(f'expected {W}x{H} frames')
    for f in frames_of(src, w, h):
        rt(f)
        sink.write((flatten(f) if args.fill else f).tobytes())
    sink.flush()
    if enc:
        enc.stdin.close(); enc.wait()
    if args.log:
        Path(args.log).write_text(json.dumps(rt.log) + '\n')
    print(f'{rt.n} frames retouched; ECC cc min logo {min(r["logo"]["cc"] for r in rt.log):.4f}, '
          f'flag {min(r["flag"]["cc"] for r in rt.log):.4f}', file=sys.stderr)


def cmd_still(args):
    from PIL import Image
    f = first_frame(args.inp)
    Retoucher()(f)
    Image.fromarray(f, 'RGBA').resize((1600, 900), Image.LANCZOS).save(args.out, 'WEBP', quality=80, method=6)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    sub = ap.add_subparsers(dest='cmd', required=True)
    b = sub.add_parser('build'); b.add_argument('--master', default=MASTER)
    r = sub.add_parser('run')
